"""LiteLLM wrapper for interacting with local LLM (llama.cpp or compatible endpoint)."""

from typing import Any

import litellm
import structlog

from src.core.config import settings

logger = structlog.get_logger()


async def generate_completion(
    messages: list[dict[str, str]],
    temperature: float | None = None,
    model: str | None = None,
    api_base: str | None = None,
) -> str:
    """Sends a completion request to LiteLLM wrapper.

    Args:
        messages: List of chat messages (role/content dicts).
        temperature: Sampling temperature for generation. Defaults to settings.llm_temperature.
        model: LLM model name. Defaults to settings.llm_model.
        api_base: LLM endpoint base URL. Defaults to settings.llm_api_base.

    Returns:
        The text response generated by the LLM.

    Raises:
        RuntimeError: If the LiteLLM completion call fails or returns empty output.
    """
    target_model = model or settings.llm_model
    target_api_base = api_base or settings.llm_api_base
    target_temp = temperature if temperature is not None else settings.llm_temperature

    logger.info(
        "calling_llm",
        model=target_model,
        api_base=target_api_base,
        temperature=target_temp,
    )

    try:
        response: Any = await litellm.acompletion(
            model=target_model,
            messages=messages,
            api_base=target_api_base,
            temperature=target_temp,
            timeout=settings.llm_timeout_seconds,
        )
        content = response.choices[0].message.content or ""
        if not content.strip():
            raise RuntimeError("LLM returned empty output")
        logger.info("llm_call_success", response_length=len(content))
        return content
    except Exception as exc:
        logger.error("llm_call_failed", error=str(exc))
        raise RuntimeError(f"LLM generation failed: {exc}") from exc
