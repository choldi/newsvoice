"""Pydantic models for the voice catalog (Phase 7.8).

A voice catalog turns "which voice narrates the public podcast" into data: a
JSON file of profiles, each describing a synthetic persona, plus a generated
manifest that records the reference audio actually produced for it. The two are
kept apart on purpose so a profile can be edited without silently invalidating
an already-generated reference.
"""

from __future__ import annotations

import re
from enum import StrEnum

from pydantic import BaseModel, Field, field_validator

#: Slug pattern for a profile name: it becomes a file name on disk.
_SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]*$")


class VoiceSource(StrEnum):
    """Where a reference voice comes from.

    Attributes:
        QWEN_DESIGN: Synthetic voice generated by Qwen3-TTS VoiceDesign from a
            text description. No natural person is involved, so no personality
            rights attach to the result.
        RECORDING: A real recording supplied by the user. Reintroduces
            personality rights, so it requires written consent and a
            transcript.
    """

    QWEN_DESIGN = "qwen_design"
    RECORDING = "recording"


class VoiceProfile(BaseModel):
    """One entry of the voice catalog.

    Attributes:
        name: Stable slug; becomes the reference file name on disk.
        label: Human-readable name for the admin GUI.
        language: ISO 639-1 code the voice speaks.
        instruct: Natural-language persona description for VoiceDesign.
        ref_text: Exact transcript of the reference sample. 250-320 chars
            yields ~14-18 s, which satisfies both the 10-30 s window ZONOS2
            needs to clone and the 3 s minimum Qwen3-TTS needs.
        role_hint: Intended use (anchor, cohost, narrator, ...).
        enabled: Whether the design flow generates this voice.
    """

    name: str = Field(..., min_length=1, max_length=64, description="Stable slug")
    label: str = Field(..., min_length=1, max_length=128, description="Human label")
    language: str = Field(..., description="ISO 639-1 code")
    instruct: str = Field(
        ..., min_length=10, max_length=2000, description="VoiceDesign persona description"
    )
    ref_text: str = Field(
        ...,
        min_length=100,
        max_length=600,
        description="Exact transcript of the reference sample",
    )
    role_hint: str = Field(default="", description="Intended role")
    enabled: bool = Field(default=True)

    @field_validator("language")
    @classmethod
    def _language_is_iso639_1(cls, value: str) -> str:
        """Normalize the voice language to a two-letter lowercase code.

        Args:
            value: Language code supplied for the profile.

        Returns:
            The lowercased code.

        Raises:
            ValueError: If the code is not a two-letter ISO 639-1 code.
        """
        code = value.strip().lower()
        if not code.isalpha() or len(code) != 2:
            raise ValueError(f"language must be a two-letter ISO 639-1 code: {value!r}")
        return code

    @field_validator("name")
    @classmethod
    def _name_is_slug(cls, value: str) -> str:
        """Keep profile names safe to use as file names.

        Args:
            value: Profile name supplied in the catalog.

        Returns:
            The lowercased slug.

        Raises:
            ValueError: If the name is not a safe slug.
        """
        slug = value.strip().lower()
        if not _SLUG.match(slug):
            raise ValueError(f"name must be a slug of [a-z0-9_-]: {value!r}")
        return slug


class VoiceManifestEntry(BaseModel):
    """Generated record for one designed voice.

    The two digest fields are the drift guard: if the profile's ``instruct`` or
    ``ref_text`` changes after the reference was generated, the digests no longer
    match and the entry is reported stale instead of being cloned silently with
    a mismatched transcript.

    Attributes:
        file: Reference WAV path relative to the voices directory.
        sha256: Digest of the WAV bytes.
        sample_rate: Sample rate of the reference audio.
        duration_seconds: Measured duration of the reference.
        design_model: Model that produced the reference.
        instruct_sha256: Digest of the profile instruct at generation time.
        ref_text_sha256: Digest of the profile ref_text at generation time.
        created_at: ISO-8601 timestamp of generation.
        modal_cost_usd: Cost of the one-off design call.
    """

    file: str = Field(..., description="Reference WAV path relative to the voices dir")
    sha256: str = Field(..., description="SHA-256 of the WAV bytes")
    sample_rate: int = Field(..., gt=0, description="Sample rate in Hz")
    duration_seconds: float = Field(..., gt=0.0, description="Duration in seconds")
    design_model: str = Field(..., description="Model that produced the reference")
    instruct_sha256: str = Field(..., description="Digest of the profile instruct")
    ref_text_sha256: str = Field(..., description="Digest of the profile ref_text")
    created_at: str = Field(..., description="ISO-8601 generation timestamp")
    modal_cost_usd: float = Field(default=0.0, ge=0.0, description="Cost of the design call")
