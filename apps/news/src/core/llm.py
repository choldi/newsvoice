"""LiteLLM wrapper for interacting with local LLM (llama.cpp or compatible endpoint)."""

from typing import Any, Literal

import litellm
import structlog

from src.core.config import settings
from src.core.tracing import trace_function

logger = structlog.get_logger()


@trace_function(component="core.llm")
async def generate_completion(
    messages: list[dict[str, str]],
    temperature: float | None = None,
    model: str | None = None,
    api_base: str | None = None,
    api_key: str | None = None,
    max_tokens: int | None = None,
    response_format: Literal["text", "json_object", "json_schema"] | None = None,
    json_schema: dict[str, Any] | None = None,
    timeout: int | None = None,
    disable_thinking: bool | None = None,
) -> str:
    """Sends a completion request to LiteLLM wrapper.

    Args:
        messages: List of chat messages (role/content dicts).
        temperature: Sampling temperature for generation. Defaults to settings.llm_temperature.
        model: LLM model name. Defaults to settings.llm_model.
        api_base: LLM endpoint base URL. Defaults to settings.llm_api_base.
        api_key: Credential for a hosted provider. Defaults to settings.llm_api_key;
            an empty key becomes the conventional "EMPTY" placeholder, which
            litellm requires even for a local OpenAI-compatible endpoint.
        max_tokens: Response budget for this call. Defaults to settings.llm_max_tokens.
        response_format: 'text' (default), 'json_object' or 'json_schema'. The
            judge passes 'json_object' so the reply can be parsed instead of
            pattern-matched.
        json_schema: JSON Schema enforced by the provider when
            response_format='json_schema'. Ignored otherwise.
        timeout: Per-call timeout in seconds. Defaults to settings.llm_timeout_seconds.
        disable_thinking: Override settings.llm_disable_thinking for this call.
            None keeps the default behaviour (off only on the free-text path).
            A JSON-mode caller that needs a deterministic answer can pass True
            explicitly: llama.cpp accepts the chat-template kwargs alongside
            ``response_format``, and ``reasoning_effort='none'`` does the same
            on Ollama. Hosted providers that reject unknown fields must leave
            it None or False.

    Returns:
        The text response generated by the LLM.

    Raises:
        RuntimeError: If the LLM completion call fails or returns empty output.
    """
    target_model = model or settings.llm_model
    target_api_base = api_base or settings.llm_api_base
    target_temp = temperature if temperature is not None else settings.llm_temperature
    target_max_tokens = max_tokens or settings.llm_max_tokens
    target_timeout = timeout or settings.llm_timeout_seconds
    # litellm's OpenAI-compatible path refuses to run without a key even when
    # the target is a local llama.cpp server (seen with litellm 1.103), so an
    # empty key becomes the conventional placeholder. A configured key —
    # argument or LLM_API_KEY — is always passed verbatim.
    target_api_key = (api_key if api_key is not None else settings.llm_api_key) or "EMPTY"

    logger.info(
        "calling_llm",
        model=target_model,
        api_base=target_api_base,
        temperature=target_temp,
        max_tokens=target_max_tokens,
        response_format=response_format or "text",
        authenticated=bool(target_api_key) and target_api_key != "EMPTY",
    )

    try:
        request_kwargs: dict[str, Any] = {
            "model": target_model,
            "messages": messages,
            "api_base": target_api_base,
            "temperature": target_temp,
            "timeout": target_timeout,
            "max_tokens": target_max_tokens,
        }
        request_kwargs["api_key"] = target_api_key
        if response_format == "json_object":
            request_kwargs["response_format"] = {"type": "json_object"}
        elif response_format == "json_schema" and json_schema is not None:
            request_kwargs["response_format"] = {
                "type": "json_schema",
                "json_schema": {"name": "response", "schema": json_schema, "strict": True},
            }
        # llama.cpp reasoning models (e.g. Qwen3) emit their answer into
        # reasoning_content and leave content empty while thinking is on.
        # Disable it and treat content as the only output channel. By default
        # only the free-text path wants this: a provider enforcing a schema or
        # JSON mode must not receive llama.cpp-only chat template kwargs. A
        # caller that knows it talks to llama.cpp can opt in explicitly.
        thinking_off = (
            settings.llm_disable_thinking if disable_thinking is None else disable_thinking
        )
        if thinking_off and (response_format is None or disable_thinking is True):
            extra_body: dict[str, Any] = {"chat_template_kwargs": {"enable_thinking": False}}
            if disable_thinking is True:
                # Ollama ignores chat_template_kwargs but disables Qwen3
                # thinking with reasoning_effort='none' (2.9s vs 69s on a
                # short prompt). llama.cpp ignores this unknown field, so
                # sending both keeps the call fast on either backend.
                extra_body["reasoning_effort"] = "none"
            request_kwargs["extra_body"] = extra_body
        response: Any = await litellm.acompletion(**request_kwargs)
        content = response.choices[0].message.content or ""
        if not content.strip():
            raise RuntimeError("LLM returned empty output")
        logger.info("llm_call_success", response_length=len(content))
        return content
    except Exception as exc:
        logger.error("llm_call_failed", error=str(exc))
        raise RuntimeError(f"LLM generation failed: {exc}") from exc
