"""Admin voices routes for the Phase 6 GUI.

Lists OmniVoice stock/cloned voices and clones a voice from a reference audio
file. Audio uploads arrive base64-encoded in JSON to avoid a `python-multipart`
runtime dependency; the VoicesService forwards them to OmniVoice as multipart.

Phase 7.8 adds the voice catalog: synthetic reference voices generated by
Qwen3-TTS VoiceDesign, stored locally and uploaded to Modal for cloning.
Phase 7.9 runs the whole catalog flow in its own Temporal namespace, so the
client below connects there rather than to the digest pipeline's namespace.
"""

import base64
from typing import Any

import structlog
from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel, Field, ValidationError
from tts_contract import VoiceCatalogResponse

from src.api.models.admin import VoiceCloneIn, VoiceCloneOut, VoicesOut
from src.api.models.voices import CustomVoiceIn, CustomVoiceOut, VoicesAllOut
from src.api.services import voice_catalog_admin
from src.api.services.tts_backends import ALLOWED_BACKENDS
from src.api.services.voice_catalog_client import VoiceCatalogRequestError
from src.api.services.voice_registry import CATEGORY_ORDER, list_all_voices
from src.api.services.voices import VoicesService
from src.core.voice_catalog import VoiceCatalogError

logger = structlog.get_logger(__name__)

router = APIRouter(tags=["admin-voices"])


@router.get("/admin/voices", response_model=VoicesOut)
async def list_stock_voices(language: str | None = None) -> VoicesOut:
    """List available stock voices, optionally filtered by language.

    Args:
        language: ISO 639-1 language filter (e.g. 'es').

    Returns:
        VoicesOut with the stock voice list.
    """
    service = VoicesService()
    voices = await service.list_stock(language=language or None)
    return VoicesOut(voices=voices)


@router.get("/admin/voices/cloned", response_model=VoicesOut)
async def list_cloned_voices() -> VoicesOut:
    """List cloned voices.

    Returns:
        VoicesOut with the cloned voice list.
    """
    service = VoicesService()
    voices = await service.list_cloned()
    return VoicesOut(voices=voices)


@router.get("/admin/voices/all", response_model=VoicesAllOut)
async def list_all_voice_options(
    engine: str | None = None,
    category: str | None = None,
) -> VoicesAllOut:
    """List every selectable voice of every engine (Phase 9.1).

    The single source behind the GUI dropdowns: cloned, generated and stock
    voices of edge, the gateway and Modal, each tagged with the engines that
    accept it so a mixed-engine selection can be rejected before generation.

    Args:
        engine: Optional canonical engine id ('edge', 'omni_voice', 'qwen3_tts',
            'zonos2') to filter by.
        category: Optional 'stock', 'cloned' or 'generated' to filter by.

    Returns:
        VoicesAllOut with the tagged voice list.

    Raises:
        HTTPException: 422 when engine or category is not a known value.
    """
    if engine and engine.strip().lower() not in ALLOWED_BACKENDS:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"engine must be one of {list(ALLOWED_BACKENDS)}: {engine!r}",
        )
    if category and category.strip().lower() not in CATEGORY_ORDER:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"category must be one of {list(CATEGORY_ORDER)}: {category!r}",
        )
    voices = await list_all_voices(engine=engine, category=category)
    return VoicesAllOut(voices=voices)


@router.post("/admin/voices/clone", response_model=VoiceCloneOut)
async def clone_voice(payload: VoiceCloneIn) -> VoiceCloneOut:
    """Clone a voice from a base64-encoded reference audio file.

    Args:
        payload: VoiceCloneIn with name, language, and base64 audio.

    Returns:
        VoiceCloneOut with the cloning response.

    Raises:
        HTTPException: 422 on invalid base64, 502 on upstream errors.
    """
    try:
        reference_audio = base64.b64decode(payload.audio_base64, validate=True)
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Invalid base64 audio: {exc}",
        ) from exc
    try:
        service = VoicesService()
        voice = await service.clone_voice(
            payload.name,
            payload.language,
            reference_audio,
            filename=payload.filename,
            ref_text=payload.ref_text,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=f"Voice cloning failed: {exc}",
        ) from exc
    return VoiceCloneOut(voice=voice)


class VoiceCatalogGenerateIn(BaseModel):
    """Input for generating reference voices.

    Attributes:
        names: Optional subset of profile names. Empty means every enabled
            profile that is missing or stale.
        upload: Also upload each generated reference to the Modal Volume.
    """

    names: list[str] = Field(default_factory=list, description="Profile names to generate")
    upload: bool = Field(default=False, description="Also upload to the Modal Volume")


@router.get("/admin/voices/catalog", response_model=VoiceCatalogResponse)
async def voice_catalog_status() -> VoiceCatalogResponse:
    """List the voice catalog with its generation status.

    The payload comes straight from the gateway, which owns the catalog: it
    carries the profiles, the manifest and which references are generated,
    missing or stale.

    Returns:
        The catalog payload.

    Raises:
        HTTPException: 502 when the gateway that owns the catalog is
            unreachable or refuses to answer it.
    """
    try:
        return await voice_catalog_admin.catalog_status()
    except VoiceCatalogError as exc:
        raise HTTPException(status_code=status.HTTP_502_BAD_GATEWAY, detail=str(exc)) from exc


@router.post("/admin/voices/catalog/generate")
async def voice_catalog_generate(payload: VoiceCatalogGenerateIn) -> dict[str, Any]:
    """Start a voice catalog generation run.

    Args:
        payload: VoiceCatalogGenerateIn with the optional name subset and the
            upload flag.

    Returns:
        Dict with the workflow id and status.

    Raises:
        HTTPException: 502 when the workflow cannot be started.
    """
    try:
        workflow_id = await voice_catalog_admin.start_generate(
            names=payload.names, upload=payload.upload
        )
    except voice_catalog_admin.VoiceCatalogAdminError as exc:
        raise HTTPException(status_code=status.HTTP_502_BAD_GATEWAY, detail=str(exc)) from exc
    return {"workflow_id": workflow_id, "status": "started"}


@router.post(
    "/admin/voices/custom",
    response_model=CustomVoiceOut,
    status_code=status.HTTP_201_CREATED,
)
async def create_custom_voice(payload: CustomVoiceIn) -> CustomVoiceOut:
    """Create an operator-authored voice profile (Phase 9.3).

    Args:
        payload: CustomVoiceIn describing the new voice.

    Returns:
        CustomVoiceOut with the saved profile and the design workflow id
        (when one could be queued).

    Raises:
        HTTPException: 422 on an invalid profile, 409 when the name is taken,
            502 when the gateway that owns the catalog is unreachable.
    """
    try:
        result = await voice_catalog_admin.create_custom_voice(payload)
    except ValidationError as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=[
                {"loc": list(error["loc"]), "msg": error["msg"], "type": error["type"]}
                for error in exc.errors()
            ],
        ) from exc
    except VoiceCatalogRequestError as exc:
        raise HTTPException(
            status_code=(
                status.HTTP_502_BAD_GATEWAY if exc.retryable else status.HTTP_409_CONFLICT
            ),
            detail=str(exc),
        ) from exc
    except VoiceCatalogError as exc:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(exc)) from exc
    return CustomVoiceOut(
        profile=result["profile"].model_dump(mode="json"),
        workflow_id=result["workflow_id"],
        start_error=result["start_error"],
    )
