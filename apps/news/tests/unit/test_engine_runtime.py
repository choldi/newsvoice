"""Unit tests for the engine runtime planner and env writer."""

import json
from pathlib import Path

import engine_runtime as runtime
import pytest
from engine_runtime import EngineRuntimeError

ENV_TARGETS = (
    Path("deploy/.env"),
    Path("apps/gateway/.env"),
    Path("apps/news/.env"),
)


@pytest.fixture
def specs() -> dict[str, runtime.RuntimeSpec]:
    """Load the real registry once per test."""
    return runtime.load_runtimes()


def test_registry_matches_canonical_contract_ids(specs: dict[str, runtime.RuntimeSpec]) -> None:
    """Every canonical contract id except mock has one runtime spec."""
    canonical, _aliases = runtime.load_contract()

    assert set(specs) == set(canonical) - {"mock"}
    assert all(spec.mode in runtime.MODES for spec in specs.values())
    assert all(set(spec.modes) <= runtime.MODES for spec in specs.values())


def test_legacy_alias_is_canonicalized(specs: dict[str, runtime.RuntimeSpec]) -> None:
    """Read-only aliases resolve before the registry lookup."""
    canonical, aliases = runtime.load_contract()

    assert runtime.canonicalize_engine("edge", aliases, canonical) == "edgetts"
    plan = runtime.resolve_plan(["qwen3"], specs=specs)
    assert plan.engines == ("qwen3_tts",)


def test_pocket_tts_with_chatterbox_has_no_conflicts(
    specs: dict[str, runtime.RuntimeSpec],
) -> None:
    """Pocket stays embedded while chatterbox runs in its own sidecar."""
    plan = runtime.resolve_plan(["pocket_tts", "chatterbox"], specs=specs)

    assert plan.conflicts == []
    assert plan.modes == {"pocket_tts": "embedded", "chatterbox": "sidecar"}
    assert plan.profiles == {"chatterbox"}
    assert "gateway-chatterbox" in plan.services
    assert plan.urls["CHATTERBOX_REMOTE_URL"] == "http://gateway-chatterbox:8000/api/v1"


def test_qwen3_tts_with_kokoro_has_no_conflicts(specs: dict[str, runtime.RuntimeSpec]) -> None:
    """The default qwen3 sidecar keeps kokoro embedded on the gateway."""
    plan = runtime.resolve_plan(["qwen3_tts", "kokoro"], specs=specs)

    assert plan.conflicts == []
    assert plan.modes["qwen3_tts"] == "sidecar"
    assert plan.modes["kokoro"] == "embedded"
    assert plan.profiles == {"qwen3"}
    assert "gateway-qwen3" in plan.services
    assert plan.urls["QWEN3_TTS_REMOTE_URL"].startswith("http://gateway-qwen3:8000")


def test_two_embedded_engines_report_a_conflict(
    specs: dict[str, runtime.RuntimeSpec],
) -> None:
    """Forcing qwen3 into the gateway collides with an embedded kokoro."""
    plan = runtime.resolve_plan(["qwen3_tts", "kokoro"], {"qwen3_tts": "embedded"}, specs=specs)

    assert plan.modes["qwen3_tts"] == "embedded"
    assert any("qwen3_tts+kokoro" in conflict for conflict in plan.conflicts)
    assert any("no pueden compartir" in conflict for conflict in plan.conflicts)


def test_non_canonicalizable_alias_is_rejected(
    specs: dict[str, runtime.RuntimeSpec],
) -> None:
    """A spelling outside the contract never reaches the registry."""
    canonical, aliases = runtime.load_contract()

    with pytest.raises(EngineRuntimeError, match="engine desconocido"):
        runtime.canonicalize_engine("pocket-tts", aliases, canonical)
    with pytest.raises(EngineRuntimeError, match="engine desconocido"):
        runtime.resolve_plan(["pocket-tts"], specs=specs)


def test_unsupported_mode_is_rejected(specs: dict[str, runtime.RuntimeSpec]) -> None:
    """An override outside the spec.modes list fails loudly."""
    with pytest.raises(EngineRuntimeError, match="no soportado por zono2"):
        runtime.resolve_plan(["zono2"], {"zono2": "embedded"}, specs=specs)


def test_env_updates_include_routing_and_urls(
    specs: dict[str, runtime.RuntimeSpec],
) -> None:
    """The loader persists routing, modes, profiles and sidecar URLs."""
    plan = runtime.resolve_plan(["pocket_tts", "chatterbox"], specs=specs)

    updates = runtime.env_updates(plan)

    assert updates["TTS_ENGINE"] == "routed"
    assert updates["TTS_EXTRA_ENGINES"] == "pocket_tts,chatterbox"
    assert json.loads(updates["TTS_RUNTIME_MODES"]) == plan.modes
    assert updates["TTS_RUNTIME_PROFILES"] == "chatterbox"
    assert updates["CHATTERBOX_REMOTE_URL"] == plan.urls["CHATTERBOX_REMOTE_URL"]


def test_write_env_dry_run_leaves_files_untouched(tmp_path: Path) -> None:
    """A dry run reports the diff without creating or editing any env file."""
    originals: dict[Path, str] = {}
    for relative in ENV_TARGETS:
        path = tmp_path / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        content = "# generated by test\nTTS_ENGINE=edgetts\nTTS_RUNTIME_MODES={}\n"
        path.write_text(content, encoding="utf-8")
        originals[path] = content
    before = sorted(str(path) for path in tmp_path.rglob("*") if path.is_file())

    plan = runtime.resolve_plan(["pocket_tts", "chatterbox"])
    changes = runtime.write_env(runtime.env_updates(plan), root=tmp_path, dry_run=True)

    assert any("TTS_ENGINE" in line for line in changes["deploy/.env"])
    assert any("TTS_RUNTIME_MODES" in line for line in changes["apps/gateway/.env"])
    assert {path: path.read_text(encoding="utf-8") for path in originals} == originals
    assert sorted(str(path) for path in tmp_path.rglob("*") if path.is_file()) == before
