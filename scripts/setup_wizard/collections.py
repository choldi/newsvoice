"""Create and summarize the per-install ``collections.toml`` file."""

from __future__ import annotations

import json
import tomllib
from pathlib import Path
from typing import Any

from .util import REPO_ROOT

__all__ = [
    "COLLECTIONS_PATH",
    "example_toml",
    "ensure_example_collection",
    "load_collections",
]

COLLECTIONS_PATH = REPO_ROOT / "apps" / "news" / "collections.toml"


def _toml_string(value: str) -> str:
    """Return ``value`` as a TOML basic string."""
    return json.dumps(value, ensure_ascii=False)


def example_toml(backend: str, language: str, voice: str) -> str:
    """Render the single example collection written by a fresh setup."""
    return (
        "# Generated by the newsvoice setup wizard.\n"
        "# Add more collections from the admin UI or edit this file.\n"
        "\n"
        "[collection_defaults]\n"
        "tts_enabled = false\n"
        "deliver_audio = false\n"
        "narration_enabled = false\n"
        'narration_strategy = "turns"\n'
        "narration_deliver_audio = true\n"
        "\n"
        "[[collections]]\n"
        'name = "example"\n'
        'time = "08:00"\n'
        'feed_urls = ["https://example.com/feed.xml"]\n'
        f"tts_backend = {_toml_string(backend)}\n"
        f"language = {_toml_string(language)}\n"
        f"voice = {_toml_string(voice)}\n"
        "delivery_channels = []\n"
        "enabled = false\n"
    )


def ensure_example_collection(
    *,
    backend: str = "edge",
    language: str = "es",
    voice: str = "",
    path: Path = COLLECTIONS_PATH,
) -> Path | None:
    """Create ``collections.toml`` with one example when it does not exist.

    Existing files are never overwritten: a real installation may already have
    hand-edited collections.
    """
    if path.exists():
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        example_toml(backend.strip() or "edge", language.strip() or "es", voice.strip()),
        encoding="utf-8",
    )
    return path


def load_collections(path: Path = COLLECTIONS_PATH) -> dict[str, Any]:
    """Parse ``collections.toml``, returning an empty mapping when absent."""
    if not path.exists():
        return {}
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return {}
